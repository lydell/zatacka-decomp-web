async function initgraph(gdriver, gmode, egavgabgi_path) {
    if (gdriver !== VGA) {
        __graphresult = 2;
        return;
    }

    if (gmode !== VGAHI) {
        __graphresult = 3;
        return;
    }

    const canvas = document.getElementById("screen");

    if (canvas === null) {
        __graphresult = 4;
        return;
    }

    canvas.style.imageRendering = "pixelated";

    // Ugly hack: Read zatacka.js’ constants to define the screen size.
    // This allows modding the screen size more easily.
    canvas.width = typeof SCREEN_WIDTH === "number" ? SCREEN_WIDTH : 640;
    canvas.height = typeof SCREEN_HEIGHT === "number" ? SCREEN_HEIGHT : 480;
    canvas.classList.add("sized");

    __ctx = canvas.getContext("2d", { alpha: false });

    if (__ctx === null || __octx === null) {
        __graphresult = 5;
        return;
    }

    try {
        await Promise.all(__all_images);
    } catch {
        __graphresult = 6;
        return;
    }

    __graphresult = grOk;
}

